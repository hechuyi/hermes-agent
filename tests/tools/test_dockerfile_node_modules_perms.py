"""contract test: dockerfile chowns runtime node_modules tree to hermes

The container drops privileges to the hermes user (uid 10000). Runtime
browser tooling and Node-backed helpers may need to inspect or update the
root node_modules tree, so it must stay writable after UID remapping.
"""
from __future__ import annotations

from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DOCKERFILE = REPO_ROOT / "Dockerfile"


def test_dockerfile_chowns_runtime_node_modules_to_hermes_user() -> None:
    text = DOCKERFILE.read_text()

    chown_lines = [
        line for line in text.splitlines()
        if "chown" in line and "hermes:hermes" in line
    ]
    assert chown_lines, (
        "Dockerfile must contain a chown -R hermes:hermes for the runtime "
        "node_modules trees; see #18800"
    )

    chown_block = "\n".join(chown_lines)

    assert "/opt/hermes/node_modules" in chown_block, (
        "/opt/hermes/node_modules must be passed to a chown -R "
        "hermes:hermes command in the Dockerfile"
    )
    assert "/opt/hermes/ui-tui" not in chown_block
